export function answerQuestion(raw) {
  const q = (raw || "").toLowerCase().normalize("NFD").replace(/\p{Diacritic}/gu, "").trim();
  if (!q) {
    return { text: "Stel gerust een vraag, bijvoorbeeld over Brightspace, je rooster of hulplijnen.", suggestions: ["Wat is Brightspace?", "Waar is mijn rooster?", "Hulp bij problemen"] };
  }

  if (/^(hoi|hallo|hey|yo|goedemorgen|goedemiddag|goedemiddag|hi)\b/.test(q)) {
    return {
      text: "Hoi! Ik ben de HAN Campus-assistent. Vraag me alles over systemen, de campus, studiepunten of waar je hulp krijgt.",
      suggestions: ["Brightspace", "Osiris", "MyX rooster", "Hulplijnen"],
    };
  }
  if (/dank|bedankt|thanks|top|perfect/.test(q)) {
    return { text: "Graag gedaan. Als je nog iets wilt weten over de HAN, stel het gerust.", suggestions: ["Campus Arnhem", "ANS toetsen", "Studiepunten"] };
  }

  const scored = knowledge.map((item) => {
    let score = 0;
    for (const key of item.keys) {
      if (q.includes(key)) score += key.length > 8 ? 4 : 3;
      const parts = key.split(" ");
      if (parts.length > 1 && parts.every((p) => q.includes(p))) score += 2;
    }
    if (q.includes(item.title.toLowerCase())) score += 5;
    return { item, score };
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score);

  if (!scored.length) {
    return {
      text: "Ik heb daar niet direct een match voor. Probeer het met een HAN-onderwerp zoals Brightspace, Osiris, Teams, Outlook, iSAS, ANS, MyX, studiepunten, campus of hulplijnen.",
      suggestions: ["Wat is Osiris?", "Waar ligt de campus?", "Hulplijnen"],
    };
  }

  const top = scored[0].item;
  const extra = scored.slice(1, 3).map((s) => s.item.title);
  let text = top.answer;
  if (top.href) text += `\n\nMeer lezen: ${top.href}`;
  return {
    text,
    suggestions: extra.length ? extra : ["Hulplijnen", "MyX", "Campus"],
  };
}
